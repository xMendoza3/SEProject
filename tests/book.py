"""
كتاب صغير مصطنع للاختبارات: صفحتين، وثلاث عناوين، وثلاث أقوال.

صغير عشان نعرف النتيجة الصحيحة لكل اختبار بالضبط،
وسريع عشان الاختبارات كلها تخلص في أقل من ثانية.
"""

from src.models import Chapter, Evidence, Opinion, Page


# ترجع صفحات الكتاب وعناوينه.
# رقم أول قول نقدر نغيّره، عشان نجرب إعادة الاستيراد بأرقام أقوال جديدة.
def make_book(first_opinion_id: int = 1):
    pages = [
        Page(1, 1, 307, "متن الصفحة الأولى", ""),
        Page(2, 1, 308, "متن الصفحة الثانية", "حواشي الصفحة الثانية"),
    ]
    verse = Evidence("quran", "﴿وَأَقِيمُوا الصَّلَاةَ﴾")
    n = first_opinion_id
    opinions = (
        Opinion(n, 2, 1, (1,), "footnote", "الحنفية قالوا: التراويح عشرون ركعة."),
        Opinion(n + 1, 2, 2, (2, 3), "footnote",
                "المالكية، والشافعية قالوا: هي سنة، لقوله تعالى: ﴿وَأَقِيمُوا الصَّلَاةَ﴾",
                (verse,)),
        Opinion(n + 2, 2, 2, (4,), "main", "الحنابلة قالوا: الأفضل فعلها جماعة."),
    )
    chapters = [
        Chapter(1, "كتاب الصلاة", 1, None, 1),
        Chapter(2, "صلاة التراويح: حكمها، ووقتها", 2, 1, 1,
                content="صلاة التراويح مشروعة عند الأئمة.", opinions=opinions),
        Chapter(3, "صلاة الوتر", 2, 1, 2),
    ]
    return pages, chapters
