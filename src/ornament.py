"""
ملف الزخرفة: شكل النجمة الثمانية، نرسمه في الواجهة وفي ملف الـ PDF.

النجمة الثمانية من أشهر أشكال الزخرفة الإسلامية، وتسمى خاتم سليمان.
نرسمها من مربعين فوق بعض: واحد مستقيم، وواحد مائل خمساً وأربعين درجة.
وحدّها الخارجي ستة عشر رأساً: ثمانية أطراف للنجمة، وثمانية زوايا داخلة بينها.

الدالة هنا تحسب الرؤوس بس، بالأرقام.
الواجهة ترسم بها نقشاً في الخلفية، وكاتب الـ PDF يرسم بها نجمة تحت العنوان.
فالشكل واحد في المكانين، ولو عدّلناه نعدّله هنا بس.
"""

import math


# رؤوس حدّ النجمة، مرتبة حول المركز، تبدأ من الطرف اللي على اليمين.
# المركز ونصف القطر بأي وحدة: نقاط في الصورة، أو مليمترات في الـ PDF.
def star_outline(cx: float, cy: float, radius: float) -> list[tuple[float, float]]:
    # نصف ضلع المربع المستقيم، لأن طرفه على بعد نصف القطر من المركز.
    half = radius / math.sqrt(2)
    # الزاوية الداخلة بين طرفين: نقطة تقاطع ضلعي المربعين.
    inner = half * (math.sqrt(2) - 1)
    # نصف أول من الحدّ بالإحداثيات حول المركز، والنصف الثاني مقلوب منه.
    quarter = [(radius, 0), (half, inner), (half, half), (inner, half),
               (0, radius), (-inner, half), (-half, half), (-half, inner)]
    points = quarter + [(-x, -y) for x, y in quarter]
    return [(cx + x, cy + y) for x, y in points]
